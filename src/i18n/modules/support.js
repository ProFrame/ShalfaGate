// Support — company ticket desk: the admin-wide queue (SupportPanel.jsx,
// ADMIN_SUPPORT) and the employee-facing "My Support Tickets" screen
// (SupportTickets.jsx, PORTAL_SUPPORT).
//
// Shared vocabulary (action_*, label_*, status_*, error_generic, module_*,
// admin_records_count, admin_nav_support) comes from platform.js/admin.js and
// is reused from there — in particular ticket STATUS labels reuse the shared
// status_open/status_inprogress/status_answered/status_closed keys directly
// (codeLabel(t, 'status', ticket.status, ...)) since support_tickets.status
// is the exact enum those keys were already seeded for (platform.js's own
// SupportConsole.jsx, the platform operator's console over the same table).
// Category/priority have no shared equivalent (pc_cat_*/pub_ticket_category_*
// are each scoped to their own surface — the platform console and the public
// site, respectively — by this codebase's own one-file-per-module rule), so
// support_cat_*/support_priority_* are this module's own.
//
// support_err_<code> keys mirror every SCREAMING_SNAKE_CASE error the
// support_* RPCs can raise (supportErrorMessage() in supportService.js maps
// one to the other, same convention operationsErrorMessage()/
// safetyErrorMessage()/assetsErrorMessage() already use).

