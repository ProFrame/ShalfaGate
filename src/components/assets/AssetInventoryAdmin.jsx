// ---------------------------------------------------------------------------
// Asset picker — enter/paste a scanned code, or search and pick from the
// list. Free text always survives as the scanned code even when nothing
// matches (an UnexpectedAsset/BarcodeMissing scan has no asset to attach to).
// Same combobox shape as FormsPortal.jsx's SearchableLibrarySelect, kept
// local here since that one is not exported.
// ---------------------------------------------------------------------------
const AssetPicker = ({ assets, lang, query, onQueryChange, onSelect, disabled }) => {
  const { t } = useLanguage();
  const [open, setOpen] = useState(false);
  const needle = query.trim().toLocaleLowerCase();
  const matches = useMemo(() => {
    if (!needle) return [];
    return assets
      .filter((asset) => `${asset.reference} ${asset.name_ar} ${asset.name_en || ''} ${asset.serial_no || ''}`.toLocaleLowerCase().includes(needle))
      .slice(0, 8);
  }, [assets, needle]);

  return (
    <div className="searchable-select" onBlur={(event) => { if (!event.currentTarget.contains(event.relatedTarget)) setOpen(false); }}>
      <Search size={18} aria-hidden="true" />
      <input
        className="form-input"
        role="combobox"
        aria-expanded={open}
        aria-autocomplete="list"
        disabled={disabled}
        value={query}
        placeholder={t('assets_scan_search_placeholder')}
        onFocus={() => setOpen(true)}
        onChange={(event) => onQueryChange(event.target.value)}
      />
      {open && needle && (
        <div className="searchable-options" role="listbox">
          {matches.map((asset) => (
            <button
              type="button"
              role="option"
              key={asset.id}
              onMouseDown={(event) => event.preventDefault()}
              onClick={() => { onSelect(asset); setOpen(false); }}
            >
              <b>{asset.reference}</b>
              <small>{pickLocalized(asset, 'name', lang)}{asset.serial_no ? ` · ${asset.serial_no}` : ''}</small>
            </button>
          ))}
          {!matches.length && <div className="searchable-empty">{t('label_no_results')}</div>}
        </div>
      )}
    </div>
  );
};

// Resolves and renders just the "last transaction" line for one asset.
// Deliberately its own component, remounted via `key={assetId}` by the
// caller: that makes a fresh fetch-on-mount for every newly selected asset
// with `loading` already true from useState's initial value, so — same
// reasoning FormsPortal.jsx documents on its own mount effect — nothing here
// ever needs to call setState synchronously inside the effect body to reset
// stale state from a previous asset.
const LastTransactionInfo = ({ assetId, locale }) => {
  const { t } = useLanguage();
  const [transaction, setTransaction] = useState(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    let cancelled = false;
    loadLastMovementForAssets([assetId]).then(({ data }) => {
      if (cancelled) return;
      setTransaction(data?.[assetId] || null);
      setLoading(false);
    });
    return () => { cancelled = true; };
  }, [assetId]);

  if (loading) return t('label_loading');
  if (!transaction) return t('assets_last_transaction_none');
  return `${t(TRANSACTION_TYPE_KEYS[transaction.transactionType] || transaction.transactionType)} · ${formatDate(transaction.performedOn, locale) || '—'}`;
};

