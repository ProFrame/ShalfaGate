const AssetInventoryAdmin = () => {
  const { t, lang, locale } = useLanguage();
  const { tenant } = useTenant();

  const [sessions, setSessions] = useState([]);
  const [sessionsLoading, setSessionsLoading] = useState(true);
  const [notice, setNotice] = useState(null);
  const [reloadToken, setReloadToken] = useState(0);
  const [selectedId, setSelectedId] = useState(null);
  const [creating, setCreating] = useState(false);
  const [statusFilter, setStatusFilter] = useState('All');
  const [search, setSearch] = useState('');

  const [custodyUnits, setCustodyUnits] = useState([]);
  const [employees, setEmployees] = useState([]);
  const [assets, setAssets] = useState([]);

  // refresh() itself sets sessionsLoading synchronously (it runs from an
  // event handler, not an effect body) before bumping the token — same
  // "caller sets loading, the effect's .then() clears it" split
  // OrgEntityScreen.jsx's own refresh() uses, so the fetch effect below
  // never calls setState synchronously in its own body.
  const refreshSessions = useCallback(() => {
    setSessionsLoading(true);
    setReloadToken((value) => value + 1);
  }, []);

  useEffect(() => {
    let cancelled = false;
    loadInventorySessions().then(({ data, error }) => {
      if (cancelled) return;
      if (error) setNotice({ tone: 'error', text: assetsErrorMessage(t, error) });
      else setSessions(data || []);
      setSessionsLoading(false);
    });
    return () => { cancelled = true; };
  }, [reloadToken, t]);

  // The directory (custody units / company assets / employee directory) does
  // not depend on the sessions filter/search state, and is shared by both
  // the create-session modal and the scanning screen — fetched once, plus
  // whenever the language changes (harmless refetch, not data loss, since
  // nothing here is user-entered).
  useEffect(() => {
    let cancelled = false;
    Promise.all([loadCustodyUnits(), loadAssets({}), loadRecipients().catch(() => [])])
      .then(([unitsResult, assetsResult, employeesData]) => {
        if (cancelled) return;
        setCustodyUnits(unitsResult.data || []);
        setAssets(assetsResult.data || []);
        setEmployees(employeesData || []);
        if (unitsResult.error || assetsResult.error) {
          setNotice({ tone: 'error', text: assetsErrorMessage(t, unitsResult.error || assetsResult.error) });
        }
      });
    return () => { cancelled = true; };
  }, [t]);

  const openSession = (id) => setSelectedId(id);
  const backToList = () => { setSelectedId(null); refreshSessions(); };

  if (selectedId) {
    return (
      <InventorySessionDetail
        sessionId={selectedId}
        tenantId={tenant?.id}
        custodyUnits={custodyUnits}
        employees={employees}
        assets={assets}
        lang={lang}
        locale={locale}
        onBack={backToList}
        onChanged={refreshSessions}
      />
    );
  }

  return (
    <>
      <SessionsListView
        sessions={sessions}
        loading={sessionsLoading}
        notice={notice}
        onDismissNotice={() => setNotice(null)}
        lang={lang}
        locale={locale}
        statusFilter={statusFilter}
        setStatusFilter={setStatusFilter}
        search={search}
        setSearch={setSearch}
        onOpen={openSession}
        onCreate={() => setCreating(true)}
      />
      {creating && (
        <CreateSessionModal
          custodyUnits={custodyUnits}
          employees={employees}
          lang={lang}
          onClose={() => setCreating(false)}
          onCreated={(id) => {
            setCreating(false);
            refreshSessions();
            setNotice({ tone: 'success', text: t('assets_session_created') });
            if (id) setSelectedId(id);
          }}
        />
      )}
    </>
  );
};

export default AssetInventoryAdmin;