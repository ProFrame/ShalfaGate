// ---------------------------------------------------------------------------
// Session detail: scope, tally, live scanning (InProgress only) and the scan
// history, plus Start/Complete session actions.
// ---------------------------------------------------------------------------
const InventorySessionDetail = ({ sessionId, tenantId, custodyUnits, employees, assets, lang, locale, onBack, onChanged }) => {
  const { t } = useLanguage();
  // `detail` doubles as the loading flag (null = not loaded yet): the effect
  // below only ever sets it from inside the async .then(), so a refresh()
  // never needs a synchronous setState at the top of the effect body — it
  // just re-fetches in the background and swaps `detail` in when ready,
  // which also means an action (start/complete/record a scan) never flashes
  // the whole screen back to a bare loading state.
  const [detail, setDetail] = useState(null);
  const [notice, setNotice] = useState(null);
  const [reloadToken, setReloadToken] = useState(0);
  const [busy, setBusy] = useState(false);
  const [completing, setCompleting] = useState(false);
  const headingRef = useRef(null);
  const focusedOnceRef = useRef(false);

  const custodyUnitsById = useMemo(() => Object.fromEntries(custodyUnits.map((unit) => [unit.id, unit])), [custodyUnits]);
  const employeesById = useMemo(() => Object.fromEntries(employees.map((employee) => [employee.id, employee])), [employees]);
  const assetsById = useMemo(() => Object.fromEntries(assets.map((asset) => [asset.id, asset])), [assets]);

  const refresh = useCallback(() => setReloadToken((value) => value + 1), []);

  useEffect(() => {
    let cancelled = false;
    loadInventorySessionDetail(sessionId).then(({ data, error }) => {
      if (cancelled) return;
      if (error) { setNotice({ tone: 'error', text: assetsErrorMessage(t, error) }); return; }
      setDetail(data);
    });
    return () => { cancelled = true; };
  }, [sessionId, reloadToken, t]);

  // Move focus to the detail heading the moment it first renders (session
  // opened), but not on every later refresh() — focusedOnceRef makes that
  // a one-shot per mount, same as this component's fresh-mount-per-session
  // lifecycle relied on elsewhere in this file.
  useEffect(() => {
    if (detail && !focusedOnceRef.current) {
      focusedOnceRef.current = true;
      headingRef.current?.focus();
    }
  }, [detail]);

  const tally = useMemo(() => {
    if (!detail) return [];
    const counts = new Map();
    detail.scans.forEach((scan) => counts.set(scan.result_status, (counts.get(scan.result_status) || 0) + 1));
    return [...counts.entries()];
  }, [detail]);

  const missingCount = tally.find(([status]) => status === 'Missing')?.[1] || 0;

  const start = async () => {
    setBusy(true);
    const { error } = await startInventorySession(sessionId);
    setBusy(false);
    if (error) { setNotice({ tone: 'error', text: assetsErrorMessage(t, error) }); return; }
    setNotice({ tone: 'success', text: t('assets_session_started') });
    refresh();
    onChanged?.();
  };

  const confirmComplete = async () => {
    setBusy(true);
    const { error } = await completeInventorySession(sessionId);
    setBusy(false);
    setCompleting(false);
    if (error) { setNotice({ tone: 'error', text: assetsErrorMessage(t, error) }); return; }
    setNotice({ tone: 'success', text: t('assets_session_completed') });
    refresh();
    onChanged?.();
  };

  if (!detail) {
    return (
      <div className="admin-content">
        <div className="assets-detail-head">
          <button type="button" className="secondary-button" onClick={onBack}><ArrowLeft aria-hidden="true" /> {t('assets_back_to_sessions')}</button>
        </div>
        <Notice notice={notice} onDismiss={() => setNotice(null)} />
        {!notice && <p className="field-note">{t('label_loading')}</p>}
      </div>
    );
  }

  const { session, units, members, scans } = detail;
  const scopeUnits = units.map((row) => custodyUnitsById[row.custody_unit_id]).filter(Boolean);
  const scopeMembers = members.map((row) => employeesById[row.user_id]).filter(Boolean);

  return (
    <div className="admin-content">
      <div className="assets-detail-head">
        <button type="button" className="secondary-button" onClick={onBack}><ArrowLeft aria-hidden="true" /> {t('assets_back_to_sessions')}</button>
      </div>

      <div className="admin-toolbar">
        <div>
          <span className="section-kicker">{session.reference}</span>
          <h1 ref={headingRef} tabIndex={-1}>{pickLocalized(session, 'name', lang) || t('assets_inventory_title')}</h1>
          <p><StatusBadge status={session.status} /></p>
        </div>
        <div className="toolbar-buttons">
          {session.status === 'Draft' && (
            <button type="button" className="primary-button" disabled={busy} onClick={start}>
              <Play aria-hidden="true" /> {t('assets_action_start_session')}
            </button>
          )}
          {session.status === 'InProgress' && (
            <button type="button" className="primary-button" disabled={busy} onClick={() => setCompleting(true)}>
              <ClipboardCheck aria-hidden="true" /> {t('assets_action_complete_session')}
            </button>
          )}
          <button type="button" className="secondary-button" onClick={refresh}><RefreshCcw aria-hidden="true" /> {t('action_refresh')}</button>
        </div>
      </div>

      <Notice notice={notice} onDismiss={() => setNotice(null)} />

      <section className="dashboard-panel">
        <h3><Calendar aria-hidden="true" /> {t('assets_session_period')}</h3>
        <div className="assets-expected-grid">
          <div><span>{t('label_from')}</span><b>{formatDate(session.start_date, locale) || '—'}</b></div>
          <div><span>{t('label_to')}</span><b>{formatDate(session.end_date, locale) || '—'}</b></div>
          <div><span>{t('label_created_on')}</span><b>{formatDate(session.created_on, locale) || '—'}</b></div>
        </div>
        {session.notes && <p className="field-note">{session.notes}</p>}
        {scopeUnits.length > 0 && (
          <>
            <p className="field-note">{t('assets_field_custody_units_scope')}</p>
            <div className="assets-chip-row">
              {scopeUnits.map((unit) => <span key={unit.id} className="assets-chip"><Boxes aria-hidden="true" /> {pickLocalized(unit, 'name', lang)}</span>)}
            </div>
          </>
        )}
        {scopeMembers.length > 0 && (
          <>
            <p className="field-note">{t('assets_field_members_scope')}</p>
            <div className="assets-chip-row">
              {scopeMembers.map((member) => <span key={member.id} className="assets-chip"><Users aria-hidden="true" /> {personName(member, lang)}</span>)}
            </div>
          </>
        )}
      </section>

      {tally.length > 0 && (
        <section className="dashboard-panel">
          <h3><ListChecks aria-hidden="true" /> {t('assets_summary_title')}</h3>
          <div className="kpi-grid compact">
            {tally.map(([status, count]) => (
              <div className="kpi-card" key={status}>
                <Package aria-hidden="true" />
                <div><span>{SCAN_RESULT_KEYS[status] ? t(SCAN_RESULT_KEYS[status]) : status}</span><b>{count}</b></div>
              </div>
            ))}
          </div>
          {session.status === 'Completed' && (
            <p className="field-note assets-missing-note"><AlertTriangle size={14} aria-hidden="true" /> {t('assets_summary_missing_generated', { count: missingCount })}</p>
          )}
        </section>
      )}

      {session.status === 'InProgress' && (
        <section className="dashboard-panel">
          <h3><Barcode aria-hidden="true" /> {t('assets_scan_title')}</h3>
          <AssetScanForm
            sessionId={sessionId}
            tenantId={tenantId}
            assets={assets}
            custodyUnitsById={custodyUnitsById}
            employeesById={employeesById}
            lang={lang}
            locale={locale}
            onRecorded={() => { setNotice({ tone: 'success', text: t('assets_scan_saved') }); refresh(); }}
          />
        </section>
      )}

      <section className="dashboard-panel">
        <h3><ClipboardList aria-hidden="true" /> {t('assets_scans_table_title')}</h3>
        <SessionScansTable scans={scans} assetsById={assetsById} employeesById={employeesById} lang={lang} locale={locale} />
      </section>

      {completing && (
        <CompleteSessionModal
          reference={session.reference}
          tally={tally}
          busy={busy}
          onClose={() => setCompleting(false)}
          onConfirm={confirmComplete}
        />
      )}
    </div>
  );
};

