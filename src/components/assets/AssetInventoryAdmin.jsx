const AssetScanForm = ({ sessionId, tenantId, assets, custodyUnitsById, employeesById, lang, locale, onRecorded }) => {
  const { t } = useLanguage();
  const [query, setQuery] = useState('');
  const [assetId, setAssetId] = useState('');
  const [resultStatus, setResultStatus] = useState('');
  const [notes, setNotes] = useState('');
  const [submitting, setSubmitting] = useState(false);
  const [error, setError] = useState('');

  const selectedAsset = useMemo(() => assets.find((asset) => asset.id === assetId) || null, [assets, assetId]);

  const selectAsset = (asset) => {
    setAssetId(asset.id);
    setQuery(asset.reference);
  };

  // Editing the text after picking a match means the person is now typing a
  // different code — the earlier match no longer applies (same "clear the
  // selection the moment free text changes" rule FormsPortal's own
  // SearchableLibrarySelect follows).
  const changeQuery = (value) => {
    setQuery(value);
    if (assetId) setAssetId('');
  };

  const reset = () => {
    setQuery(''); setAssetId(''); setResultStatus(''); setNotes('');
  };

  const submit = async (event) => {
    event.preventDefault();
    if (!resultStatus) { setError(t('assets_scan_pick_result')); return; }
    if (!query.trim() && !assetId) { setError(t('assets_scan_need_code_or_asset')); return; }
    setSubmitting(true);
    setError('');
    const { error: scanError } = await recordInventoryScan(sessionId, resultStatus, {
      scannedCode: query.trim() || null,
      assetId: assetId || null,
      notes: notes.trim() || null,
    });
    setSubmitting(false);
    if (scanError) { setError(assetsErrorMessage(t, scanError)); return; }
    reset();
    onRecorded();
  };

  const expectedCustodyUnit = selectedAsset ? custodyUnitsById[selectedAsset.current_custody_unit_id] : null;
  const expectedCustodian = selectedAsset ? employeesById[selectedAsset.current_custodian_user_id] : null;

  return (
    <form className="assets-scan-form" onSubmit={submit}>
      <label className="field-label">{t('assets_scan_field_label')}
        <AssetPicker assets={assets} lang={lang} query={query} onQueryChange={changeQuery} onSelect={selectAsset} disabled={submitting} />
      </label>

      {selectedAsset && (
        <div className="assets-expected-grid">
          <div><span>{t('assets_expected_name')}</span><b>{pickLocalized(selectedAsset, 'name', lang)}</b></div>
          <div><span>{t('assets_expected_custody_unit')}</span><b>{expectedCustodyUnit ? pickLocalized(expectedCustodyUnit, 'name', lang) : '—'}</b></div>
          <div><span>{t('assets_expected_custodian')}</span><b>{expectedCustodian ? personName(expectedCustodian, lang) : '—'}</b></div>
          <div>
            <span>{t('assets_last_transaction_title')}</span>
            <b><LastTransactionInfo key={selectedAsset.id} assetId={selectedAsset.id} locale={locale} /></b>
          </div>
        </div>
      )}

      <div className="field-label">
        {t('assets_result_status_label')}
        <div className="approval-action-options" role="group" aria-label={t('assets_result_status_label')}>
          {SELECTABLE_SCAN_RESULTS.map((code) => (
            <button
              type="button"
              key={code}
              className={`approval-action-option ${resultStatus === code ? 'active' : ''}`}
              aria-pressed={resultStatus === code}
              onClick={() => setResultStatus(code)}
            >
              <span><b>{t(SCAN_RESULT_KEYS[code])}</b></span>
            </button>
          ))}
        </div>
      </div>

      <label className="field-label">{t('assets_field_notes')}
        <textarea className="form-input" value={notes} onChange={(event) => setNotes(event.target.value)} />
      </label>

      {selectedAsset && tenantId && (
        <div className="assets-scan-photo">
          <p className="field-note">{t('assets_scan_photo_hint')}</p>
          <AttachmentsPanel
            tenantId={tenantId}
            entityType="Asset"
            entityId={selectedAsset.id}
            area="assets"
            layer="Extended"
            listFn={listAssetAttachments}
          />
        </div>
      )}

      {error && <div className="modal-error"><X aria-hidden="true" />{error}</div>}

      <div className="assets-scan-submit">
        <button type="submit" className="primary-button" disabled={submitting}>
          <ClipboardCheck aria-hidden="true" /> {submitting ? t('label_loading') : t('assets_action_record_scan')}
        </button>
      </div>
    </form>
  );
};

