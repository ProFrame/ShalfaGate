// Asset Inventory — session-based physical counting/verification, the admin
// screen for the Assets Management module (FourthUpdate.md).
// Route: admin/asset-inventory · permission: Assets.Inventory · rank 3.
//
// Flow: list sessions -> create a Draft session (bilingual name, date range,
// custody units in scope, member users) -> start it -> scan assets one at a
// time against their expected custody unit/custodian/last transaction
// (result: Found/Damaged/WrongLocation/WrongCustodian/NeedsMaintenance/
// Disposed/UnexpectedAsset/BarcodeMissing — never Missing, that is
// system-generated only) -> complete the session, which shows a summary of
// counts by result_status including how many rows were auto-generated as
// Missing by asset_inventory_session_complete().
//
// Data access only through src/data/assetsService.js, plus loadRecipients()
// from approvalService.js for the employee directory — the exact same reuse
// every other admin screen already makes for that list (ApprovalAdmin.jsx,
// ApprovalChain.jsx).

