// ---------------------------------------------------------------------------
// Local vocabulary maps — same pattern as ApprovalAdmin.jsx's STATUS_KEYS:
// codes are stored/compared as-is, only the label shown to a person is
// translated. Draft/InProgress/Cancelled reuse the platform-wide status_*
// vocabulary exactly (that is what they mean); 'Completed' has no existing
// generic equivalent (status_closed means something else) so it is the one
// module-owned addition.
// ---------------------------------------------------------------------------
const SESSION_STATUS_FILTERS = ['All', ...INVENTORY_SESSION_STATUSES];

// Every code asset_inventory_scan() accepts as a manual result. 'Missing' is
// deliberately excluded from the selectable set — the RPC itself rejects a
// manual 'Missing' scan (MISSING_IS_SYSTEM_GENERATED); it only ever appears
// already-recorded, generated by asset_inventory_session_complete().
const SELECTABLE_SCAN_RESULTS = INVENTORY_SCAN_RESULTS.filter((code) => code !== 'Missing');

const SCAN_RESULT_KEYS = {
  Found: 'assets_scan_found',
  Missing: 'assets_scan_missing',
  Damaged: 'assets_scan_damaged',
  WrongLocation: 'assets_scan_wronglocation',
  WrongCustodian: 'assets_scan_wrongcustodian',
  NeedsMaintenance: 'assets_scan_needsmaintenance',
  Disposed: 'assets_scan_disposed',
  UnexpectedAsset: 'assets_scan_unexpectedasset',
  BarcodeMissing: 'assets_scan_barcodemissing',
};

// asset_transactions can carry a few types createAssetTransaction() itself
// never writes (Dispose/MaintenanceOut/MaintenanceReturn come from the
// disposal and maintenance RPCs/triggers instead) — "last transaction" may
// legitimately show any of them.
const TRANSACTION_TYPE_KEYS = {
  Receive: 'assets_txn_receive', Issue: 'assets_txn_issue', Transfer: 'assets_txn_transfer',
  Return: 'assets_txn_return', Lost: 'assets_txn_lost', Found: 'assets_txn_found',
  Reserve: 'assets_txn_reserve', Release: 'assets_txn_release', Dispose: 'assets_txn_dispose',
  MaintenanceOut: 'assets_txn_maintenanceout', MaintenanceReturn: 'assets_txn_maintenancereturn',
};

const personName = (person, lang) => pickLocalized(person, 'name', lang) || person?.full_name || '';

const StatusBadge = ({ status }) => {
  const { t } = useLanguage();
  const key = SESSION_STATUS_KEYS[status];
  return <span className={`status-badge status-${String(status || '').toLowerCase()}`}>{key ? t(key) : status}</span>;
};

const ScanResultBadge = ({ result }) => {
  const { t } = useLanguage();
  const key = SCAN_RESULT_KEYS[result];
  return <span className={`scan-badge scan-${String(result || '').toLowerCase()}`}>{key ? t(key) : result}</span>;
};

const Notice = ({ notice, onDismiss }) => {
  const { t } = useLanguage();
  if (!notice) return null;
  return (
    <div className={`inline-message ${notice.tone === 'error' ? 'error' : ''}`} role="status" aria-live="polite">
      {notice.tone === 'error' ? <X aria-hidden="true" /> : <Check aria-hidden="true" />}
      {notice.text}
      <button type="button" onClick={onDismiss} aria-label={t('action_close')}><X aria-hidden="true" /></button>
    </div>
  );
};

