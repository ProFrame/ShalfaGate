const SessionsListView = ({ sessions, loading, notice, onDismissNotice, lang, locale, statusFilter, setStatusFilter, search, setSearch, onOpen, onCreate }) => {
  const { t } = useLanguage();
  const headingRef = useRef(null);

  // This view unmounts entirely while a session's detail is open (see the
  // selectedId branch in AssetInventoryAdmin below), so every mount here is
  // either the initial load or "came back from detail" — same one-effect
  // shape AssetsPortal.jsx's own list/detail toggle already uses.
  useEffect(() => { headingRef.current?.focus(); }, []);

  const filtered = useMemo(() => {
    const needle = search.trim().toLocaleLowerCase();
    return sessions.filter((session) => (
      (statusFilter === 'All' || session.status === statusFilter)
      && (!needle || `${session.reference} ${session.name_ar} ${session.name_en || ''}`.toLocaleLowerCase().includes(needle))
    ));
  }, [sessions, statusFilter, search]);

  return (
    <div className="admin-content">
      <div className="admin-toolbar">
        <div>
          <span className="section-kicker">{t('module_assets')}</span>
          <h1 ref={headingRef} tabIndex={-1}><ClipboardList className="admin-title-icon" aria-hidden="true" /> {t('assets_inventory_title')}</h1>
          <p>{t('assets_inventory_intro')}</p>
        </div>
        <div className="toolbar-actions">
          <button type="button" className="primary-button" onClick={onCreate}><Plus aria-hidden="true" /> {t('assets_inventory_new_session')}</button>
        </div>
      </div>

      <Notice notice={notice} onDismiss={onDismissNotice} />

      <div className="data-controls">
        <div className="search-control">
          <Search aria-hidden="true" />
          <input
            value={search}
            onChange={(event) => setSearch(event.target.value)}
            placeholder={t('assets_inventory_search_placeholder')}
            aria-label={t('action_search')}
          />
        </div>
        <div className="segmented" role="group" aria-label={t('label_status')}>
          {SESSION_STATUS_FILTERS.map((status) => (
            <button
              type="button"
              key={status}
              aria-pressed={statusFilter === status}
              className={statusFilter === status ? 'active' : ''}
              onClick={() => setStatusFilter(status)}
            >
              {status === 'All' ? t('label_all') : t(SESSION_STATUS_KEYS[status])}
            </button>
          ))}
        </div>
      </div>

      <div className="data-table-wrap">
        <table className="enterprise-table">
          <thead>
            <tr>
              <th>{t('assets_column_reference')}</th>
              <th>{t('label_status')}</th>
              <th>{t('assets_session_period')}</th>
              <th aria-label={t('label_actions')} />
            </tr>
          </thead>
          <tbody>
            {filtered.map((session) => (
              <tr key={session.id}>
                <td><div><b>{session.reference}</b><small>{pickLocalized(session, 'name', lang)}</small></div></td>
                <td><StatusBadge status={session.status} /></td>
                <td>{formatDate(session.start_date, locale) || '—'} – {formatDate(session.end_date, locale) || '—'}</td>
                <td>
                  <div className="table-actions">
                    <button type="button" onClick={() => onOpen(session.id)} title={t('action_open')} aria-label={t('action_open')}><Eye aria-hidden="true" /></button>
                  </div>
                </td>
              </tr>
            ))}
            {!loading && !filtered.length && (
              <tr><td colSpan="4"><div className="empty-table"><PackageSearch aria-hidden="true" /><b>{t('label_no_results')}</b><span>{t('assets_session_empty_hint')}</span></div></td></tr>
            )}
            {loading && <tr><td colSpan="4">{t('label_loading')}</td></tr>}
          </tbody>
        </table>
      </div>
    </div>
  );
};

